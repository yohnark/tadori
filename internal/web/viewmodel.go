// ProgressEvent is the deliberately small, UI-owned event shape used by the
// view endpoint. It is not a runtime/session contract. A future session or
// SSE adapter can translate its events into this shape without changing the
// canonical diagnostic model or the view renderer.
type ProgressEvent struct {
	ProbeName string            `json:"probe_name,omitempty"`
	State     string            `json:"state"`
	Status    model.ProbeStatus `json:"status,omitempty"`
}

// ProgressRunner is an optional adapter for a runner that can report
// presentation progress on the legacy synchronous view endpoint. The
// session/SSE runtime has its own published contract and is used by the
// browser's normal workflow; this adapter remains useful to embedders and
// deterministic tests without coupling them to session storage.
type ProgressRunner func(context.Context, model.Target, func(ProgressEvent)) model.DiagnosticReport

// DiagnosticViewModel is an additive presentation projection. Report is the
// canonical source of truth; every other field is derived from it and can be
// discarded and rebuilt. CanonicalJSON is generated by report.MarshalJSON so
// the inspector does not re-serialize or reinterpret raw evidence in the
// browser.
type DiagnosticViewModel struct {
	Report         model.DiagnosticReport   `json:"report"`
	CanonicalJSON  string                   `json:"canonical_json"`
	NetworkContext *NetworkContextView      `json:"network_context,omitempty"`
	Overall        OverallView              `json:"overall"`
	Progress       []ProgressEvent          `json:"progress"`
	Probes         []ProbeView              `json:"probes"`
	Findings       []FindingView            `json:"findings"`
	Evidence       []EvidenceView           `json:"evidence"`
	Paths          []PathView               `json:"paths"`
	Comparisons    []ProtocolComparisonView `json:"comparisons"`
}

