func labelForFailureReason(reason model.FailureReason) string {
	if reason == model.FailureReasonNone {
		return "No failure"
	}
	words := strings.Split(string(reason), "_")
	for index, word := range words {
		if word == "" {
			continue
		}
		words[index] = strings.ToUpper(word[:1]) + word[1:]
	}
	return strings.Join(words, " ")
}

